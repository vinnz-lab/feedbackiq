/** The PDF guide is reachable from the sign-in page and the in-app guide (run via run-ws-suites.sh). */
import { chromium } from "playwright";
const base = process.env.BASE || "http://localhost:4000";
let fail = 0;
const check = (ok, n, d = "") => { console.log(`${ok ? "  ✓" : "  ✗"} ${n}${d ? " — " + d : ""}`); if (!ok) fail++; };
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1300, height: 900 }, acceptDownloads: true });
const page = await ctx.newPage();
await page.goto(base + "/login", { waitUntil: "networkidle" });
const link = page.getByRole("link", { name: /Download the getting started guide/ });
check((await link.count()) === 1, "sign-in page links to the PDF");
check((await link.getAttribute("href")) === "/insight-hub-guide.pdf", "…at the right address");
const r = await fetch(base + "/insight-hub-guide.pdf");
const bytes = Buffer.from(await r.arrayBuffer());
check(r.status === 200 && r.headers.get("content-type") === "application/pdf" && bytes.subarray(0, 4).toString() === "%PDF", "the PDF is served as a real PDF without signing in", `${(bytes.length / 1e6).toFixed(1)} MB`);
const [dl] = await Promise.all([page.waitForEvent("download"), link.click()]);
check(dl.suggestedFilename() === "Insight-Hub-Getting-Started.pdf", "clicking it downloads the guide", dl.suggestedFilename());
await page.getByRole("link", { name: /Download the getting started/ }).waitFor({ state: "visible" }).catch(() => {});
await page.getByRole("button", { name: /Choose|Sign in|Continue/ }).first().waitFor({ state: "visible", timeout: 2000 }).catch(() => {});
await page.goto(base + "/login", { waitUntil: "networkidle" });
await page.click("text=Jamie Lee");
await page.waitForURL("**/dashboard", { timeout: 20000 });
await page.evaluate(() => { for (const k of Object.keys(localStorage)) if (k.startsWith("ih-guide-hidden")) localStorage.removeItem(k); });
await page.goto(base + "/dashboard", { waitUntil: "networkidle" });
const inApp = page.getByRole("link", { name: /Download the getting started guide/ });
check((await inApp.count()) >= 1, "the in-app Getting Started guide links to the PDF");
await b.close();
console.log(fail ? `${fail} FAILED` : "all passed");
process.exit(fail ? 1 : 0);
