import { PrivacyLink } from "@/components/privacy-link";
import type { Metadata } from "next";
import { desc, eq } from "drizzle-orm";
import { getDb, schema } from "@/db";
import { FullLogo } from "@/components/brand";
import { DigestView } from "@/components/digest-view";
import type { DigestContent } from "@/lib/digest-content";
import { computeScore } from "@/lib/score";
import { latestDigest, openShareLink } from "@/lib/sharing-data";

export const dynamic = "force-dynamic";
// Private links: never indexed, and the address isn't passed on to sites it links to.
export const metadata: Metadata = { title: { absolute: "Shared from Insight Hub" }, robots: { index: false, follow: false }, referrer: "no-referrer" };

const COLUMNS = [
  ["review", "Under review"],
  ["planned", "Planned"],
  ["progress", "In progress"],
  ["shipped", "Shipped"],
] as const;

function Shell({ children, workspace, what }: { children: React.ReactNode; workspace?: string; what?: string }) {
  return (
    <div className="min-h-screen bg-bg px-6 py-8">
      <div className="mx-auto max-w-5xl">
        <div className="mb-6 flex flex-wrap items-center gap-3">
          <FullLogo size={30} />
          {workspace && (
            <span className="ml-auto rounded-[var(--radius-pill)] border border-border bg-surface px-3 py-1 text-[12px] text-muted">
              <b className="text-fg">{workspace}</b> · {what} · read-only
            </span>
          )}
        </div>
        {children}
        <p className="mt-8 text-center text-[11.5px] text-muted">Shared from Insight Hub — every customer voice, one clear roadmap.</p>
        <PrivacyLink className="mt-1" />
      </div>
    </div>
  );
}

export default async function SharePage({ params }: { params: Promise<{ token: string }> }) {
  const { token } = await params;
  const link = await openShareLink(token);
  if (!link) {
    return (
      <Shell>
        <div className="mx-auto max-w-md rounded-[var(--radius-card)] border border-border bg-surface p-8 text-center shadow-[var(--shadow)]">
          <div className="text-[16px] font-semibold">This link has been switched off or doesn&apos;t exist</div>
          <p className="mt-1 text-[13px] text-muted">Ask whoever shared it with you for a new one.</p>
        </div>
      </Shell>
    );
  }
  const ws = link.workspace;

  if (link.kind === "digest") {
    const d = await latestDigest(ws.id);
    return (
      <Shell workspace={ws.name} what="Feedback digest">
        <div className="mx-auto max-w-3xl">
          {d?.content ? (
            <DigestView c={d.content as DigestContent} createdAt={d.createdAt} footer={`Generated by Insight Hub for ${ws.name} · grounded in approved customer feedback`} />
          ) : (
            <div className="rounded-[var(--radius-card)] border border-border bg-surface p-8 text-center text-[13px] text-muted shadow-[var(--shadow)]">No digest has been written yet. Check back later.</div>
          )}
        </div>
      </Shell>
    );
  }

  // Roadmap: titles, status and scores only — no quotes, customer names or Jira details.
  const db = await getDb();
  const rows = await db
    .select({ e: schema.enhancements, themeTitle: schema.themes.title })
    .from(schema.enhancements)
    .leftJoin(schema.themes, eq(schema.enhancements.themeId, schema.themes.id))
    .where(eq(schema.enhancements.workspaceId, ws.id))
    .orderBy(desc(schema.enhancements.createdAt));
  const items = rows
    .map(({ e, themeTitle }) => ({ id: e.id, title: themeTitle ?? e.title, status: e.status, demand: e.demand, score: computeScore(e.benefit, e.effort, e.demand) }))
    .sort((a, b) => b.score - a.score);

  return (
    <Shell workspace={ws.name} what="Roadmap">
      <h1 className="mb-1 text-[26px] font-bold tracking-tight">Roadmap</h1>
      <p className="mb-5 text-[13px] text-muted">Prioritised from customer feedback · updated live</p>
      <div className="grid grid-cols-1 gap-3 md:grid-cols-4">
        {COLUMNS.map(([k, label]) => {
          const col = items.filter((i) => i.status === k);
          return (
            <section key={k} aria-label={label} className="rounded-[var(--radius-card)] border border-border bg-surface p-3 shadow-[var(--shadow)]">
              <h2 className="mb-2 text-[11px] font-bold uppercase tracking-wide text-muted">
                {label} · {col.length}
              </h2>
              <div className="flex flex-col gap-2">
                {col.length === 0 && <p className="text-[12px] text-muted">Nothing here yet.</p>}
                {col.map((i) => (
                  <div key={i.id} className="rounded-[10px] border border-border bg-bg p-2.5">
                    <div className="text-[13px] font-semibold leading-snug">{i.title}</div>
                    <div className="mt-1 text-[11.5px] text-muted">
                      Score {i.score.toFixed(1)} · {i.demand} customer mention{i.demand === 1 ? "" : "s"}
                    </div>
                  </div>
                ))}
              </div>
            </section>
          );
        })}
      </div>
    </Shell>
  );
}
