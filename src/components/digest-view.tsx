import type { DigestContent } from "@/lib/digest-content";

/** One digest, as shown in the app and on its public share page. */
export function DigestView({ c, createdAt, footer = "Generated by Insight Hub · grounded in approved feedback" }: { c: DigestContent; createdAt: Date | null; footer?: string }) {
  return (
    <div className="rounded-[var(--radius-card)] border border-border bg-surface p-8 shadow-[var(--shadow)]">
      <div className="text-[12px] font-semibold uppercase tracking-wide text-indigo">✨ Generated {createdAt ? new Date(createdAt).toLocaleString("en-GB") : ""}</div>
      <h2 className="mt-1 text-[22px] font-bold leading-tight tracking-tight">{c.headline}</h2>
      <p className="mt-3 text-[14px] leading-relaxed text-muted">{c.summary}</p>

      {c.sections?.map((s, i) => (
        <div key={i} className="mt-6">
          <h3 className="mb-2 text-[12px] font-bold uppercase tracking-wide text-indigo">{s.heading}</h3>
          <ul className="flex flex-col gap-1.5">
            {s.items.map((it, k) => (
              <li key={k} className="ml-4 list-disc text-[13.5px]">
                {it}
              </li>
            ))}
          </ul>
        </div>
      ))}

      {c.quotes?.length > 0 && (
        <div className="mt-6">
          <h3 className="mb-2 text-[12px] font-bold uppercase tracking-wide text-indigo">Notable quotes</h3>
          <div className="flex flex-col gap-2.5">
            {c.quotes.map((q, i) => (
              <div key={i} className="rounded-[0_8px_8px_0] border-l-[3px] border-indigo bg-bg px-4 py-2.5 text-[13px] italic">
                “{q.text}”<div className="mt-1 text-[11.5px] not-italic text-muted">— {q.by}</div>
              </div>
            ))}
          </div>
        </div>
      )}

      {c.roadmap && (
        <div className="mt-6">
          <h3 className="mb-2 text-[12px] font-bold uppercase tracking-wide text-indigo">Roadmap snapshot</h3>
          <div className="grid grid-cols-2 gap-2 sm:grid-cols-4">
            {([["review", "Under review"], ["planned", "Planned"], ["progress", "In progress"], ["shipped", "Shipped"]] as const).map(([k, label]) => (
              <div key={k} className="rounded-[10px] border border-border bg-bg p-3 text-center">
                <div className="text-[18px] font-extrabold">{c.roadmap[k]}</div>
                <div className="text-[10.5px] uppercase tracking-wide text-muted">{label}</div>
              </div>
            ))}
          </div>
        </div>
      )}

      <p className="mt-8 border-t border-border pt-3 text-[11.5px] text-muted">{footer}</p>
    </div>
  );
}
